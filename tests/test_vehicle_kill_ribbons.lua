local create=dofile(assert(arg[1]))
local KILLS=3566519756
local TANK,FRV='16474112801385B6','CC21C7FFD3EBEFB9'
local CANNON,MG='1FA1F596769225C2','439F9E65C18567DA'
local allowed={[TANK]={kind='vehicle_body',known_player_call_in=true},
    [FRV]={kind='vehicle_body',known_player_call_in=true}}
local function snapshot(total,rows)
    local sources={}
    for hash,n in pairs(rows or {})do sources[hash]={[KILLS]=n}end
    return {totals={[KILLS]=total},sources=sources}
end
local tests=0
local function check(name,fn)fn();tests=tests+1;print('PASS '..name)end
check('first late-join body totals are a baseline and no old awards are reconstructed',function()
    local api=create(allowed,KILLS)
    local total,added,baseline=api:sample(snapshot(1403,{[TANK]=154,[CANNON]=75,[MG]=231}),77)
    assert(total==0 and added==0 and baseline and next(api.sources)==nil)
    total,added=api:sample(snapshot(1404,{[TANK]=155,[CANNON]=75,[MG]=231}),77)
    assert(total==1 and added==1 and api.sources[TANK]==1)
    total,added=api:sample(snapshot(1404,{[TANK]=155,[CANNON]=75,[MG]=231}),77)
    assert(total==1 and added==0)
end)
check('only exact parent hashes count and mounted cannon MG unknown source gaps remain separate',function()
    local api=create(allowed,KILLS);api:sample(snapshot(0),77)
    local total,added=api:sample(snapshot(15,{[TANK]=2,[FRV]=3,[CANNON]=4,[MG]=5,['AAAAAAAAAAAAAAAA']=1}),77)
    assert(total==5 and added==5)
    total,added=api:sample(snapshot(537,{[TANK]=2,[FRV]=3,[CANNON]=4,[MG]=5,['AAAAAAAAAAAAAAAA']=1}),77)
    assert(total==5 and added==0,'522 kills without a hash cannot be guessed as a body source')
    total,added=api:sample(snapshot(538,{[TANK]=2,[FRV]=3,[CANNON]=4,[MG]=6,['AAAAAAAAAAAAAAAA']=1}),77)
    assert(total==5 and added==0)
end)
check('a source first seen after an empty mission baseline counts its native growth',function()
    local api=create(allowed,KILLS);api:sample(snapshot(0),77)
    local total,added=api:sample(snapshot(4,{[TANK]=4}),77)
    assert(total==4 and added==4)
end)
check('missing source blocks retain identity and cannot replay their previous kills',function()
    local api=create(allowed,KILLS);api:sample(snapshot(0),77)
    api:sample(snapshot(5,{[TANK]=5}),77)
    local total,added=api:sample(snapshot(7),77)
    assert(total==5 and added==0)
    total,added=api:sample(snapshot(7,{[TANK]=5}),77)
    assert(total==5 and added==0)
    assert(api:sample(snapshot(7,{[TANK]=8}),77)==nil,'redistribution without native kill growth is not a new crush')
    total,added=api:sample(snapshot(8,{[TANK]=8}),77)
    assert(total==5 and added==0)
    total,added=api:sample(snapshot(9,{[TANK]=9}),77)
    assert(total==6 and added==1)
end)
check('read gaps baseline the next valid frame and preserve already earned ribbons',function()
    local api=create(allowed,KILLS);api:sample(snapshot(0),77)
    api:sample(snapshot(5,{[TANK]=5}),77);api:gap()
    local total,added,baseline=api:sample(snapshot(8,{[TANK]=8}),77)
    assert(total==5 and added==0 and baseline)
    total,added=api:sample(snapshot(10,{[TANK]=10}),77)
    assert(total==7 and added==2)
end)
check('source decreases and native counter resets never award the reset value',function()
    local api=create(allowed,KILLS);api:sample(snapshot(0),77)
    api:sample(snapshot(10,{[TANK]=10}),77)
    local total,added=api:sample(snapshot(12,{[TANK]=2}),77)
    assert(total==10 and added==0)
    total,added=api:sample(snapshot(13,{[TANK]=3}),77)
    assert(total==11 and added==1)
    total,added=api:sample(snapshot(2,{[TANK]=2}),77)
    assert(total==11 and added==0)
    total,added=api:sample(snapshot(3,{[TANK]=3}),77)
    assert(total==12 and added==1)
end)
check('death with unchanged mission counters and player identity rebases cannot duplicate sources',function()
    local api=create(allowed,KILLS);api:sample(snapshot(0),77)
    api:sample(snapshot(5,{[TANK]=5}),77)
    local total,added=api:sample(snapshot(5,{[TANK]=5}),77)
    assert(total==5 and added==0,'death itself does not reset this source-total consumer')
    total,added=api:sample(snapshot(6,{[TANK]=6}),77)
    assert(total==6 and added==1)
    total,added=api:sample(snapshot(6,{[TANK]=6}),88)
    assert(total==6 and added==0)
    total,added=api:sample(snapshot(7,{[TANK]=7}),88)
    assert(total==7 and added==1)
    api:reset();total,added=api:sample(snapshot(7,{[TANK]=7}),88)
    assert(total==0 and added==0,'new mission baseline never replays the prior match')
end)
check('invalid sources and totals reject instead of fabricating vehicle kills',function()
    local api=create(allowed,KILLS);api:sample(snapshot(0),77)
    for _,value in ipairs({-1,1.5,math.huge,0/0})do
        assert(api:sample(snapshot(5,{[TANK]=value}),77)==nil)
        assert(api.total==0 and api.added==0)
    end
    assert(api:sample(snapshot(3,{[TANK]=4}),77)==nil)
    assert(api:sample(snapshot(3,{[TANK]=2}),nil)==nil)
    assert(api:sample(nil,77)==nil)
    local total,added=api:sample(snapshot(3,{[TANK]=2}),77)
    assert(total==0 and added==0,'recovery establishes an explicit baseline')
end)
check('a table with unreviewed or non-parent entries is refused at construction',function()
    assert(not pcall(create,{[CANNON]={kind='mounted_weapon',known_player_call_in=true}},KILLS))
    assert(not pcall(create,{[TANK]={kind='vehicle_body',known_player_call_in=false}},KILLS))
    assert(not pcall(create,{['tank']={kind='vehicle_body',known_player_call_in=true}},KILLS))
end)
print('Vehicle body kill ribbon cases passed: '..tests)
