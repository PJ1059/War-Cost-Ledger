local create=dofile(assert(arg[1]))
local fire,gas,gun='AAAAAAAAAAAAAAAA','BBBBBBBBBBBBBBBB','CCCCCCCCCCCCCCCC'
local a=create({[fire]={fire=true},[gas]={poison=true}})
assert(a:native(fire,164,true));assert(a:element('fire')==164)
for _=1,164 do a:observe_element('fire',fire);a:observe_source(fire)end
assert(a:element('fire')==164 and a:weapon(fire)==164,'native and target overlap must not double')
a:observe_element('fire');assert(a:element('fire')==165,'new no-source ground fire must not vanish under large native total')
a:native(fire,1);assert(a:element('fire')==166)
a:observe_source(gun);assert(a:weapon(gun)==1)
a:native(gun,1);assert(a:weapon(gun)==1,'later native credit must reconcile')
a:observe_source(gun);assert(a:weapon(gun)==2,'target-bound missing native source can fill gap')
a:native(gun,4);assert(a:weapon(gun)==5)
a:native(gas,3,true);a:observe_element('poison',gas);assert(a:element('poison')==3)
a:observe_source(gun,gas)
local correction=a:reassignments();assert(correction[gas]==1)
correction[gas]=100;assert(a:reassignments()[gas]==1,'correction snapshots must not share state')
a:observe_source(gun,nil,true)
assert(a:reassignments()._unknown==1,'inherited source without raw identity keeps an anonymous correction allowance')
a:observe_source(gun)
assert(a:reassignments()._unknown==1,'direct known source without a raw identity is not a reassignment')
a:observe_element('fire',gun);assert(a:element('fire')==167,'explicit element works without fire-weapon trait')
assert(a:element('poison')==3 and a:element('other')==0)
assert(not a:native('unknown',1)and not a:observe_source('unknown')and not a:observe_element('other',gun))
a:reset();assert(a:weapon(gun)==0 and a:element('fire')==0 and a:element('poison')==0)
assert(next(a:reassignments())==nil)
print('PASS: source max reconciliation, native fire coverage, anonymous ground fire, poison, delayed source credit and reset.')
