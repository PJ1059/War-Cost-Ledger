local function fixture(options)
    local opts={sequence=1,names={[A]={name_zh='测试步枪'},[B]={name_zh='测试炮'}},
        enemies={[E]={name_zh='武斗虫'},[F]={name_zh='食腐虫'}}}
    for k,v in pairs(options or {})do opts[k]=v end
    local api=create(opts);local f={api=api}
    function f:death(t,id,kind,extra)
        local e={sequence=1,local_killer=true,observed='dead_state',entity_id=id or 1,type=kind or E}
        for k,v in pairs(extra or {})do e[k]=v end
        return api:on_death(e,t)
    end
    function f:batch(t,kills,sources,extra)
        local e={sequence=1,local_player=true,kills=kills or 1,sources=sources or{{type=A,kills=kills or 1}}}
        for k,v in pairs(extra or {})do e[k]=v end
        return api:on_batch(e,t)
    end
    function f:stats(t,kills,sources,extra)
        local e={sequence=1,local_player=true,kills=kills or 0,sources=sources or{}}
        for k,v in pairs(extra or {})do e[k]=v end
        return api:on_stats(e,t)
    end
    function f:row(t)return api:snapshot(t).items[1]end
    return f
end
