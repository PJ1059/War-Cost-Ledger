"""Generate the six-region Lua profile and a pure Python reference.

No Game access, native execution or registration. The installed 0.4.23 addon
continues using its frozen profile until a new package is built and installed.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('six_fixed_uw',
    Path(__file__).with_name('hit_world_contact_ap_physical_unwind_copy.py'))
mapper = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mapper)
BASE, ALLOCATION = 0x180000000, 0x190000000
OFFSETS = {'frame': 0x100, 'world': 0x1000, 'contact': 0x4000,
           'ap': 0x9000, 'dispatcher': 0x9400, 'physical': 0xA000}


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def lua_hex(raw):
    encoded = raw.hex()
    return '\n    '.join('"' + encoded[i:i+240] + '"' +
        (' ..' if i+240 < len(encoded) else '') for i in range(0, len(encoded), 240))


def generate(parity_path, expected_parity_sha, output):
    parity_raw = parity_path.read_bytes()
    parity = json.loads(parity_raw)
    if sha(parity_raw) != expected_parity_sha or parity['status'] != 'PASS' or parity['differences']:
        raise ValueError('SIX_OWNED_PARITY_SOURCE')
    prior_raw = (ROOT/'dist/hit-unwind-parity-owned-20261013-v1/report.json').read_bytes()
    prior = json.loads(prior_raw)
    prior_sha = 'b7bd925f5ab822689a56ad5d201c7c3e049d4787f89ca9b2f00602f4b5c2532a'
    if sha(prior_raw) != prior_sha or prior['status'] != 'PASS' or prior['differences']:
        raise ValueError('SIX_PRIOR_OWNED_PARITY_SOURCE')
    source, evidence = mapper.code_copy.load_sources()
    metadata = mapper.load_sources()
    old = mapper.previous.load_sources()
    layout = {n: ALLOCATION + o for n, o in OFFSETS.items()}
    built = mapper.build(BASE, layout, ALLOCATION + 0xB000, ALLOCATION + 0xB400)
    names = list(mapper.REGIONS)
    indexes = {n: i+1 for i, n in enumerate(names)}
    # Original physical and dispatcher packet includes code plus metadata. Code
    # already receives the full region comparison; duplicate only its metadata.
    packet = (ROOT/'dist'/mapper.SOURCE_DIRECTORY/'callsite.bin').read_bytes()
    pins = [(name, rva, old['raw'][offset:offset+size])
            for name, rva, size, offset in mapper.previous.SOURCE_RANGES]
    pins += [('physical_RF7', 0x409AE64, packet[244:328]),
             ('physical_UW180', 0x2511668, packet[328:508]),
             ('dispatcher_RF', 0x408E150, packet[508:520]),
             ('dispatcher_UW', 0x24FC4AC, packet[520:532]),
             ('AP_RF', 0x408E078, struct.pack('<III', *mapper.AP_RF)),
             ('AP_UW48', 0x24FC2E0, metadata['blocks']['ap'])]
    fields = []
    for r in built['code']['manifest']['relocations']:
        n, begin = r['region'], mapper.REGIONS[r['region']][0]
        if r['kind'] == 'switch_rva32':
            offset, end, target_region, mode = r['offset'], 0, n, 2
        else:
            offset = r['old_pc'] - BASE - begin + r['field_offset']
            end = r['old_pc'] - BASE - begin + r['instruction_size']
            target_region = r['destination_region']
            mode = 3 if r['kind'] == 'switch_table_disp32' else 1
        target = r['old_target'] - BASE
        if target_region:
            target -= mapper.REGIONS[target_region][0]
        fields.append((indexes[n], offset, r['width'], end,
                       indexes.get(target_region, 0), target, mode))
    code_bytes, metadata_bytes = sum(map(len, source.values())), sum(len(p[2]) for p in pins)
    if (len(fields), code_bytes, metadata_bytes) != (1574, 29824, 1068):
        raise ValueError('SIX_FIXED_PROFILE_COUNTS')
    lines = ['-- Generated by tools/native/generate_hit_six_code_copy_profile.py.',
             '-- Fixed six-region data; no import-time native activity.', 'return {',
             ' version=2, allocation_bytes=0xD000, code_page_bytes=0xB000,',
             ' wrapper_offset=0, cas_offset=0x40, unwind_offset=0xB000, table_offset=0xB400, counter_offset=0xC000,',
             ' field_count=1574, RF_count=28, chain_count=22, unwind_bytes=732,',
             ' full_code_bytes=29824, full_metadata_bytes=1068, read_budget_bytes=73728, read_budget_calls=64,',
             f' metadata_sha="{mapper.SOURCE_BIN_SHA}", metadata_json_sha="{mapper.SOURCE_JSON_SHA}",',
             f' owned_parity_sha="{expected_parity_sha}", owned_parity_PCs={sum(parity["tested_PC_counts"].values())},',
             f' prior_owned_parity_sha="{prior_sha}", prior_owned_parity_PCs=5824,',
             ' regions={']
    for n in names:
        rva, size, _ = mapper.REGIONS[n]
        lines += [f'  {{name="{n}",rva={rva},offset={OFFSETS[n]},length={size},sha="{sha(source[n])}",hex=',
                  '    '+lua_hex(source[n])+'},']
    lines += [' }, source_metadata={']
    for name, rva, raw in pins:
        lines.append(f'  {{name="{name}",rva={rva},length={len(raw)},hex="{raw.hex()}"}},')
    lines += [' }, unwind_hex=', '    '+lua_hex(metadata['raw'])+',',
              ' -- region,fieldOffset,width,pcEndOffset,targetRegion(0=external),targetOffsetOrRVA,mode',
              ' fields={']
    for row in sorted(fields):
        lines.append('  {'+','.join(map(str, row))+'},')
    lines += [' }, runtime_functions={']
    for n in names:
        begin = mapper.REGIONS[n][0]
        uw_begin, _, _, uw_offset = mapper.UW_BLOCKS[n]
        for a, c, u in metadata['records'][n]:
            lines.append(f'  {{{indexes[n]},{a-begin},{c-begin},{uw_offset+u-uw_begin}}},')
    lines += [' }, chains={']
    for n in names:
        begin = mapper.REGIONS[n][0]
        uw_begin, _, _, uw_offset = mapper.UW_BLOCKS[n]
        for node in metadata['nodes'][n]:
            if node['flags'] != 4:
                continue
            a, c, u = node['chain']
            lines.append(f'  {{{uw_offset+node["offset"]+node["tail_offset"]},{indexes[n]},{a-begin},{c-begin},{uw_offset+u-uw_begin}}},')
    lines += [' },', '}']
    output.mkdir(parents=True, exist_ok=True)
    profile = ('\n'.join(lines)+'\n').encode('utf8')
    (output/'native-code-copy-profile.lua').write_bytes(profile)
    mapper.export_build(built, output/'python-reference')
    (output/'generation.json').write_text(json.dumps({
        'source_code_packets': evidence, 'metadata': metadata['evidence'],
        'owned_parity_sha256': expected_parity_sha, 'synthetic_base': BASE,
        'synthetic_allocation': ALLOCATION, 'profile_sha256': sha(profile),
        'fields': len(fields), 'RF_count': 28, 'chain_count': 22,
        'code_bytes': code_bytes, 'metadata_bytes': metadata_bytes,
        'Game_accessed': False}, indent=2)+'\n', encoding='utf8')
    print(json.dumps({'profile': str((output/'native-code-copy-profile.lua').resolve()),
                     'code_bytes': code_bytes, 'RF_count': 28, 'Game_accessed': False}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--parity-report', type=Path, required=True)
    parser.add_argument('--parity-sha', required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate(args.parity_report, args.parity_sha, args.output)
