"""Generate only the fixed Lua code-copy profile and offline owned reference."""
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('fixed_uw', Path(__file__).with_name('hit_world_contact_unwind_copy.py'))
mapper = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mapper)
BASE, ALLOCATION = 0x180000000, 0x190000000
OFFSETS = {'frame': 0x100, 'world': 0x1000, 'contact': 0x4000}
PARITY_SHA = 'b7bd925f5ab822689a56ad5d201c7c3e049d4787f89ca9b2f00602f4b5c2532a'


def h(raw):
    return hashlib.sha256(raw).hexdigest()


def lua_hex(raw):
    encoded = raw.hex()
    return '\n    '.join('"' + encoded[i:i+240] + '"' + (' ..' if i+240 < len(encoded) else '')
                         for i in range(0, len(encoded), 240))


def main():
    source, evidence = mapper.code_copy.load_sources()
    metadata = mapper.load_sources()
    parity_path = ROOT / 'dist/hit-unwind-parity-owned-20261013-v1/report.json'
    parity_raw = parity_path.read_bytes()
    parity = json.loads(parity_raw)
    if h(parity_raw) != PARITY_SHA or parity['status'] != 'PASS' or parity['differences'] != []:
        raise ValueError('OWNED_PARITY_SOURCE')
    layout = {n: ALLOCATION + o for n, o in OFFSETS.items()}
    built = mapper.build(BASE, layout, ALLOCATION + 0x9000, ALLOCATION + 0x9400)
    region_names = list(mapper.code_copy.REGIONS)
    indexes = {n: i+1 for i, n in enumerate(region_names)}
    lines = ['-- Generated by tools/native/generate_hit_code_copy_profile.py; fixed-source data only.',
             '-- No import-time native access, allocation or request.', 'return {',
             ' version=1, allocation_bytes=0xB000, code_page_bytes=0x9000,',
             ' wrapper_offset=0, cas_offset=0x40, unwind_offset=0x9000, table_offset=0x9400, counter_offset=0xA000,',
             ' metadata_sha="'+mapper.SOURCE_BIN_SHA+'", metadata_json_sha="'+mapper.SOURCE_JSON_SHA+'",',
             ' owned_parity_sha="'+PARITY_SHA+'", owned_parity_PCs=5824,', ' regions={']
    for n in region_names:
        rva, size, _ = mapper.code_copy.REGIONS[n]
        lines += [f'  {{name="{n}",rva={rva},offset={OFFSETS[n]},length={size},sha="{h(source[n])}",hex=',
                  '    '+lua_hex(source[n])+'},']
    lines += [' }, source_metadata={']
    for name, rva, size, offset in mapper.SOURCE_RANGES:
        lines += [f'  {{name="{name}",rva={rva},length={size},hex="{metadata["raw"][offset:offset+size].hex()}"}},']
    uw = metadata['raw'][708:720] + metadata['raw'][216:440] + metadata['raw'][440:696]
    lines += [' }, unwind_hex=', '    '+lua_hex(uw)+',',
              ' -- region,fieldOffset,width,pcEndOffset,targetRegion(0=external),targetOffsetOrRVA,mode(1=rel,2=RVA32,3=disp32RVA)',
              ' fields={']
    fields = []
    for r in built['code']['manifest']['relocations']:
        n = r['region']; begin = mapper.code_copy.REGIONS[n][0]
        if r['kind'] == 'switch_rva32':
            offset, end, target_region, mode = r['offset'], 0, 'world', 2
        else:
            offset = r['old_pc'] - BASE - begin + r['field_offset']
            end = r['old_pc'] - BASE - begin + r['instruction_size']
            target_region = r['destination_region']
            mode = 3 if r['kind'] == 'switch_table_disp32' else 1
        target = r['old_target'] - BASE
        if target_region: target -= mapper.code_copy.REGIONS[target_region][0]
        fields.append((indexes[n], offset, r['width'], end, indexes.get(target_region, 0), target, mode))
    for row in sorted(fields):
        lines.append('  {'+','.join(map(str,row))+'},')
    lines += [' }, runtime_functions={']
    for n in region_names:
        begin = mapper.code_copy.REGIONS[n][0]
        uw_begin, _, _, uw_offset = mapper.UW_BLOCKS[n]
        for a, c, u in metadata['records'][n]:
            lines.append(f'  {{{indexes[n]},{a-begin},{c-begin},{uw_offset+u-uw_begin}}},')
    lines += [' }, chains={']
    for n in region_names:
        begin = mapper.code_copy.REGIONS[n][0]
        uw_begin, _, _, uw_offset = mapper.UW_BLOCKS[n]
        for node in metadata['nodes'][n]:
            if node['flags'] != 4: continue
            a,c,u = node['chain']
            lines.append(f'  {{{uw_offset+node["offset"]+node["tail_offset"]},{indexes[n]},{a-begin},{c-begin},{uw_offset+u-uw_begin}}},')
    lines += [' },', '}']
    (ROOT/'src/native-code-copy-profile.lua').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    out = ROOT/'dist/native-code-copy-probe-owned-20261013'
    out.mkdir(parents=True, exist_ok=True)
    mapper.export_build(built, out/'python-reference')
    (out/'generation.json').write_text(json.dumps({'source_code_packets':evidence,
        'metadata':metadata['evidence'],'owned_parity_sha256':PARITY_SHA,'synthetic_base':BASE,
        'synthetic_allocation':ALLOCATION,'profile_sha256':h((ROOT/'src/native-code-copy-profile.lua').read_bytes()),
        'fields':len(fields),'RF_count':19,'chain_count':16,'Game_accessed':False},indent=2)+'\n')
    print('Generated fixed Lua profile; fields='+str(len(fields))+' RF=19 chain=16; Game_accessed=false')


if __name__ == '__main__':
    main()
